export function getNews(slug: string) {
  return news.find((item) => item.slug === slug);
}

export function formatNewsDate(iso: string) {
  return new Intl.DateTimeFormat("ru-RU", {
    day: "numeric",
    month: "long",
    year: "numeric",
  }).format(new Date(iso + "T12:00:00"));
}
